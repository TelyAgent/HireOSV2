/**
 * `t(source)` / `t(source, key)` — returns the Chinese string when the
 * language is `zh` and an entry exists, else the English source unchanged.
 * A namespaced `key` wins over the bare source so colliding status labels
 * can each get their own wording.
 */
export function translate(lang: "en" | "zh", source: string, key?: string): string {
  if (lang !== "zh") return source;
  if (key && ZH[key]) return ZH[key];
  return ZH[source] ?? source;
}
