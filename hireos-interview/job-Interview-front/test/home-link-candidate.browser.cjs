const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.INTERVIEW_TEST_URL || 'http://127.0.0.1:5197/interview/';

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('https://fonts.googleapis.com/**', route => route.abort());
    await page.route('**/account/api/**', route => route.fulfill({ json: { loginRequired: false }, status: route.request().url().endsWith('/me') ? 401 : 200 }));
    const job = { id: 'job', title: 'Test engineer', recruitingStatus: 'unknown', createdAt: '2026-10-01T00:00:00Z' };
    let rows = [], links = 0, failUpload = false, failLink = false;
    let releaseUpload;
    let uploadBarrier = Promise.resolve();
    await page.route('**/interview/api/jobs', route => route.fulfill({ json: [job] }));
    await page.route('**/interview/api/tasks', route => route.fulfill({ json: rows }));
    await page.route('**/interview/api/materials', async route => {
      await uploadBarrier;
      await route.fulfill(failUpload ? { status: 503, json: { code: 'REQUEST_FAILED' } } : { json: { id: 'resume-1', name: 'resume.txt', readStatus: 'available', text: 'Synthetic candidate', errorCode: null, segments: [] } });
    });
    await page.route('**/interview/api/jobs/job/tasks', route => {
      links++;
      assert.deepEqual(route.request().postDataJSON(), { materialId: 'resume-1' });
      if (failLink) return route.fulfill({ status: 503, json: { code: 'REQUEST_FAILED' } });
      rows = [{ id: 'task', jobId: job.id, job: { title: job.title }, status: 'draft', candidate: { id: 'candidate', name: 'Synthetic candidate' }, rounds: [], createdAt: job.createdAt, resume: null }];
      return route.fulfill({ json: { id: 'task' } });
    });
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Cluster by JD', exact: true }).click();
    await page.getByText('0 candidates', { exact: true }).waitFor();
    await page.getByRole('button', { name: /More statistics/i }).click();
    const metrics = page.locator('#additional-statistics').getByTestId('home-metric');
    await metrics.last().waitFor();
    assert.equal((await metrics.allTextContents()).filter(v => v === 'Unavailable').length, 8);
    assert.equal((await metrics.allTextContents()).filter(v => v === '1').length, 1);
    job.recruitingStatus = 'open';
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Cluster by JD', exact: true }).click();
    await page.getByText('0 candidates', { exact: true }).waitFor();
    assert.equal((await metrics.allTextContents()).filter(v => v === '0').length, 1);
    assert.equal((await metrics.allTextContents()).filter(v => v === 'Unavailable').length, 8);
    console.log('PASS #307 unavailable source is not zero; available unknown-role counts show 1 then 0');

    const open = () => page.getByRole('button', { name: 'Link candidate', exact: true }).first().click();
    const dialog = page.getByRole('dialog');
    await open();
    assert.equal(await dialog.getByRole('button', { name: 'Link candidate', exact: true }).isDisabled(), true);
    const choose = dialog.getByRole('button', { name: 'Choose resume', exact: true });
    await choose.focus();
    const chooserEvent = page.waitForEvent('filechooser');
    await page.keyboard.press('Enter');
    await (await chooserEvent).setFiles([]);
    await dialog.getByText('No file selected', { exact: true }).waitFor();
    await page.waitForFunction(() => {
      const modal = document.querySelector('.ant-modal');
      return modal && !/appear|enter|leave/.test(modal.className) && getComputedStyle(modal).opacity === '1';
    });
    await page.screenshot({ path: '/tmp/hireos-link-candidate-desktop.png', animations: 'disabled' });
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(links, 0);
    await open();
    const file = { name: 'resume.txt', mimeType: 'text/plain', buffer: Buffer.from('Synthetic candidate') };
    failUpload = true;
    await dialog.locator('input[type=file]').setInputFiles(file);
    await dialog.getByRole('alert').waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Link candidate', exact: true }).isDisabled(), true);
    failUpload = false;
    uploadBarrier = new Promise(resolve => { releaseUpload = resolve; });
    await dialog.getByRole('button', { name: 'Retry', exact: true }).click();
    await dialog.getByRole('status').waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Link candidate', exact: true }).isDisabled(), true);
    releaseUpload();
    await dialog.getByRole('status').waitFor({ state: 'hidden' });
    failLink = true;
    await dialog.getByRole('button', { name: 'Link candidate', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    failLink = false;
    await dialog.getByRole('button', { name: 'Link candidate', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByText('1 candidate', { exact: true }).waitFor();
    await page.getByRole('table').getByText('Synthetic candidate', { exact: true }).waitFor();
    assert.equal(new URL(page.url()).pathname, new URL(base).pathname);
    await open();
    await dialog.locator('input[type=file]').setInputFiles(file);
    await dialog.getByRole('status').waitFor({ state: 'hidden' });
    await dialog.getByRole('button', { name: 'Link candidate', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByText('1 candidate', { exact: true }).waitFor();
    assert.equal(links, 3);
    await page.setViewportSize({ width: 390, height: 844 });
    await open();
    await dialog.waitFor();
    await page.waitForFunction(() => {
      const modal = document.querySelector('.ant-modal');
      return modal && !/appear|enter|leave/.test(modal.className) && getComputedStyle(modal).opacity === '1';
    });
    const bounds = await dialog.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
    assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= 844);
    await page.screenshot({ path: '/tmp/hireos-link-candidate-mobile.png', animations: 'disabled' });
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.deepEqual(errors, []);
    console.log('PASS #313 cancel, upload failure/retry, loading gate, link failure/retry, same-job refresh and duplicate response');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
